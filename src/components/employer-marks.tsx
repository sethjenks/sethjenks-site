type EmployerToken = {
  kind: "space" | "word";
  value: string;
};

export type EmployerHit = {
  id: EmployerId;
  start: boolean;
};

export function employerMarks(tokens: readonly EmployerToken[]): Map<number, EmployerHit> {
  const marks = new Map<number, EmployerHit>();

  for (let index = 0; index < tokens.length; index += 1) {
    if (tokens[index]?.kind !== "word" || marks.has(index)) {
      continue;
    }

    for (const employer of EMPLOYERS) {
      const wordIndexes = matchPhrase(tokens, index, employer.words);
      if (!wordIndexes) {
        continue;
      }

      wordIndexes.forEach((wordIndex, wordNumber) => {
        marks.set(wordIndex, { id: employer.id, start: wordNumber === 0 });
      });
      break;
    }
  }

  return marks;
}

function matchPhrase(
  tokens: readonly EmployerToken[],
  start: number,
  words: readonly string[],
): number[] | null {
  const wordIndexes: number[] = [];
  let cursor = start;

  for (const word of words) {
    while (tokens[cursor]?.kind === "space") {
      cursor += 1;
    }

    const token = tokens[cursor];
    if (!token || token.kind !== "word" || bareWord(token.value) !== word) {
      return null;
    }

    wordIndexes.push(cursor);
    cursor += 1;
  }

  return wordIndexes;
}

function bareWord(value: string) {
  return value.replace(/[.,]$/, "");
}

